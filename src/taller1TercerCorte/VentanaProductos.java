    public void cargarDatosArchivotxt(){
        BufferedReader bufferedReader = null;
        try{
            File file = new File("D:\\Documents\\NetBeansProjects\\GIT POO\\calculadora\\src\\taller1TercerCorte\\productosTaller1.txt");
            bufferedReader = new BufferedReader(new FileReader(file));
            String linea;
            int i = 0;
            String[][] matriz = new String[4][4];
            String[] columnas = {"NOMBRE", "PRECIO","CATEGORIA","CODIGO",};
            while((linea = bufferedReader.readLine()) != null){
                    String[] lista = new String[3];
                    lista = linea.split(",");
                    matriz[i][0] = lista[0];
                    matriz[i][1] = lista[1];
                    matriz[i][2] = lista[2];
                    matriz[i][3] = lista[3];
                    i++;
            }
            DefaultTableModel modelo = new DefaultTableModel(matriz, columnas);
            tablaProductos.setModel(modelo);
        }catch(Exception e){
            System.out.println(e.getMessage());
        }finally{
            try{
                if(bufferedReader != null){
                    bufferedReader.close();
                }    
            }catch(Exception ex){
                System.out.println(ex.getMessage());
            }
        }
    }

