    private void botonGuardarProductoMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_botonGuardarProductoMouseClicked
        String nombre = campoNombreProducto.getText().trim();
        String precio = campoPrecioProducto.getText().trim();
        String categoria = campoCategoriaProducto.getText().trim();
        String codigo = campoCodigoProducto.getText().trim();

        
        if (nombre.isEmpty() || precio.isEmpty() || categoria.isEmpty() || codigo.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Todos los campos son obligatorios", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }
        campoNombreProducto.setText("");
        campoPrecioProducto.setText("");
        campoCategoriaProducto.setText("");
        campoCodigoProducto.setText("");

        
        BufferedWriter bufferedWriter = null;
        try {
            File file = new File("D:\\Documents\\NetBeansProjects\\GIT POO\\calculadora\\src\\taller1TercerCorte\\productosTaller1.txt");
            bufferedWriter = new BufferedWriter(new FileWriter(file, true));

            
            bufferedWriter.write(nombre + "," + precio + "," + categoria + "," + codigo);
            bufferedWriter.newLine();

        } catch (Exception e) {
            System.out.println(e.getMessage());
        } finally {
            try {
                if (bufferedWriter != null) {
                    bufferedWriter.close();
                    cargarDatosArchivotxt();
                }
            } catch (Exception e) {
                System.out.println(e.getMessage());
            }
        }
        
    }//GEN-LAST:event_botonGuardarProductoMouseClicked

