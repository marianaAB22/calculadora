    private void botonGuardarTXTMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_botonGuardarTXTMouseClicked
        String id = campoId.getText();
        String nombre = campoNombre.getText();
        String correo = campoCorreo.getText();
        
        try{
            
            File file = new File("personas.txt");
            file.createNewFile();
            FileWriter writer = new FileWriter(file);
            BufferedWriter bufferedWriter = new BufferedWriter(writer);
            bufferedWriter.write(id);
            bufferedWriter.write("\n"+nombre);
            bufferedWriter.write("\n"+correo+"\n");
            bufferedWriter.close();
            
        } catch (IOException ex) {
            Logger.getLogger(ventana.class.getName()).log(Level.SEVERE, null, ex);
        }
        
        campoId.setText("");
        campoNombre.setText("");
        campoCorreo.setText("");
        
    }//GEN-LAST:event_botonGuardarTXTMouseClicked

