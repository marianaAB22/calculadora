    private void botonGuardarJSONMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_botonGuardarJSONMouseClicked
        String id = campoId.getText();
        String nombre = campoNombre.getText();
        String correo = campoCorreo.getText();

        try{
            File file = new File("personas.json");
            file.createNewFile();
            FileWriter writer = new FileWriter(file);
            BufferedWriter bufferedWriter = new BufferedWriter(writer);
            Gson gson = new Gson();
            String identi = gson.toJson(id);
            String name = gson.toJson(nombre);
            String email = gson.toJson(correo);
            bufferedWriter.write(identi);
            bufferedWriter.write(name);
            bufferedWriter.write(email);
        }catch(Exception e){
            System.out.println(e.getMessage());
        }
    }//GEN-LAST:event_botonGuardarJSONMouseClicked

